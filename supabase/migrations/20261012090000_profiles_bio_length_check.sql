-- F4-C1: public.profiles.bio への長さ・形式CHECK制約の追加
--
-- 対象（本migrationに含まれるもの）:
--   - public.profiles.bio への追加CHECK制約（profiles_bio_check）のみ
--
-- 本migrationに含まれないもの:
--   - display_name・username等、既存カラムの制約変更（一切変更しない）
--   - RLS・GRANT・RPCの変更（profiles_update_own・列単位GRANTはいずれも無変更）
--   - fan_sinceへの制約（F4-C1の対象外。未来日付の扱いはF4-C2のフォーム・
--     更新処理側で検討する）
--   - avatar_urlへの制約（F4-Cの対象外）
--   - 既存データの一括更新（本migration適用時点でbioがNULL以外の行は
--     検証プロジェクト・本番ともに0件であることを事前確認済み。6節参照）
--   - 他テーブルの変更
--
-- 20260920022832_core_schema.sql（001）〜20260928150000_song_images_policies.sql
-- （047）はいずれも変更しない。
--
-- -----------------------------------------------------------------------------
-- 確定仕様（F4-C設計・PM確定）:
--   - NULLを許可する（自己紹介は任意項目）。
--   - NULL以外は1〜300 Unicodeコードポイント（char_length基準。PostgreSQLの
--     char_length()はUTF-8データベースでも「文字（コードポイント）」単位で
--     数える。絵文字等のUTF-16サロゲートペア文字も1文字として数えられる。
--     JavaScript側の `.length`（UTF-16コード単位）とは基準が異なるため、
--     アプリ側の文字数カウンター・バリデーションは `Array.from(bio).length`
--     等、コードポイント単位の数え方を用いてこのDB制約と一致させること
--     （F4-C設計報告書で確認済み）。
--   - 前後の半角スペース（U+0020）・全角スペース（U+3000）を禁止する
--     （display_nameの既存制約 profiles_display_name_signup_check /
--     20260920120721_signup_db_foundation.sql と同じ方針）。
--   - LF（chr(10)、改行）は許可する（自己紹介文の段落分けに使うことを想定）。
--   - CR（chr(13)）・TAB（chr(9)）は、アプリ側で保存前に正規化する設計
--     （例：CRLF/単独CRをLFへ変換、TABを除去または他の文字へ置換してから
--     送信する）とし、DB側では他のASCII制御文字と同じ扱いで禁止する。
--     アプリ側の正規化処理に不具合があり、万一CR・TABを含む値がそのまま
--     送信された場合でも、本制約が最終防衛線としてUPDATE全体を拒否する。
--   - 上記以外のASCII制御文字（chr(1)〜chr(9)、chr(11)〜chr(31)）および
--     DEL（chr(127)）を禁止する。NUL（chr(0)）はPostgreSQLのtext型が
--     値として保持できないため判定不要（20260920120721_signup_db_foundation.sql
--     の既存コメントと同じ前提）。
--   - HTML（`<script>`等のタグ風の文字列）は、本制約では特別扱いしない
--     （通常の文字列としてそのまま保存可能）。アプリ側の表示層（Reactの
--     デフォルトエスケープ、dangerouslySetInnerHTMLを使わない設計）で
--     安全性を担保する方針とする。
--
-- -----------------------------------------------------------------------------
-- PostgreSQL上での動作検証（本migration作成前に実施。破壊的操作なし）:
--   実テーブルへのALTER/INSERT/UPDATEは一切行わず、本制約と全く同一の
--   bool式を、検証プロジェクトに対する読み取り専用のSELECT（VALUES句による
--   18件のリテラル文字列への適用）で検証した。NULL・空文字・半角/全角
--   スペースのみ・前後半角/全角スペース・300/301文字（通常文字・絵文字
--   各300/301コードポイント）・LF/CR/TAB/ASCII制御文字/DELを含む文字列・
--   HTMLタグ風文字列の全18ケースで、期待どおりのPASS/FAIL結果を実機で
--   確認済み（F4-C1報告書に結果一覧を記載）。
--
--   既存データへの影響も読み取り専用で確認済み：検証プロジェクト・本番
--   プロジェクトとも、現時点でbioがNULL以外の行は0件（本制約に違反する
--   既存行も0件）。
-- -----------------------------------------------------------------------------
alter table public.profiles
  add constraint profiles_bio_check
  check (
    bio is null
    or (
      char_length(bio) between 1 and 300
      and left(bio, 1) <> chr(32)
      and right(bio, 1) <> chr(32)
      and left(bio, 1) <> chr(12288)
      and right(bio, 1) <> chr(12288)
      and bio !~ (
        '[' || chr(1) || '-' || chr(9) ||
        chr(11) || '-' || chr(31) ||
        chr(127) || ']'
      )
    )
  );
